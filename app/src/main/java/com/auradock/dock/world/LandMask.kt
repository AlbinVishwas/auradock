 */
object LandMask {
    const val COLUMNS = 56
    const val ROWS = 20
    val rows: List<String> = listOf(
        ".........##.####...######................#####..........",
        "#.#############.##..####......####..####################",
        "..############..#...##.......##########################.",
        ".......########.###........#.#####################..#...",
        "........##########.#.......#######################......",
        ".........########..........###.##.###############.......",
        ".........#######...........###...##############..#......",
        "..........#####...........#####################.........",
        "...........##............############..#######..........",
        "............###..........############..##..##...........",
        "................###.......##########........#...........",
        "................####.........######........#............",
        "...............######........#####...........#...#......",
        "................#######.......####................#.....",
        "................######........####.#...........##.#.....",
        ".................#####........####.#..........#####.....",
        ".................###..........###.............######....",
        ".................###..........................#..###....",
        "................##......................................",
        "................##......................................"
    )

    fun isLand(column: Int, row: Int): Boolean = rows[row][column] == '#'
}
